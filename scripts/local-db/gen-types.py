#!/usr/bin/env python3
"""
Generate src/types/database.ts from the local test database, in the same
shape `supabase gen types typescript` produces, for the tables, enums and
RPCs in the public schema.

Stand-in for when the Supabase CLI is unavailable. Once a project exists,
replace with:
    npx supabase gen types typescript --project-id <ref> --schema public > src/types/database.ts

Usage: scripts/local-db/run-tests.sh && python3 scripts/local-db/gen-types.py
"""
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DB = os.environ.get("TEST_DB", "dd_test")
PSQL = ["psql", "-X", "-q", "-tA", "-h", os.environ.get("PGHOST", "127.0.0.1"),
        "-p", os.environ.get("PGPORT", "54322"), "-U", os.environ.get("PGUSER", "postgres"), "-d", DB]

# RPCs exposed to the app. Test helpers living in public are excluded.
RPC_PREFIXES = ("get_", "admin_", "staff_", "hold_", "release_", "confirm_", "cancel_", "submit_", "mark_", "register_", "withdraw_", "join_", "leave_", "report_")


def q(sql: str):
    out = subprocess.run(PSQL + ["-c", sql], check=True, capture_output=True, text=True).stdout.strip()
    return json.loads(out) if out else []


enums = q("""
select coalesce(json_agg(json_build_object('name', t.typname, 'values',
  (select json_agg(e.enumlabel order by e.enumsortorder) from pg_enum e where e.enumtypid = t.oid))
  order by t.typname), '[]')
from pg_type t join pg_namespace n on n.oid = t.typnamespace
where n.nspname = 'public' and t.typtype = 'e'
""")
enum_names = {e["name"] for e in enums}

columns = q("""
select coalesce(json_agg(json_build_object(
  'table', c.table_name, 'column', c.column_name, 'nullable', c.is_nullable = 'YES',
  'default', c.column_default is not null, 'identity', c.is_identity = 'YES',
  'generated', c.identity_generation, 'data_type', c.data_type, 'udt', c.udt_name)
  order by c.table_name, c.ordinal_position), '[]')
from information_schema.columns c
join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
""")

functions = q("""
select coalesce(json_agg(json_build_object(
  'name', p.proname,
  'args', (select coalesce(json_agg(json_build_object('name', a.name, 'type', format_type(a.type, null),
            'has_default', a.ord > p.pronargs - p.pronargdefaults) order by a.ord), '[]')
           from unnest(coalesce(p.proargnames[1:p.pronargs], array[]::text[]), p.proargtypes::oid[])
                with ordinality as a(name, type, ord)),
  'table_cols', (select json_agg(json_build_object('name', a.name, 'type', format_type(a.type, null)) order by a.ord)
                 from unnest(p.proargnames, p.proallargtypes, p.proargmodes) with ordinality as a(name, type, mode, ord)
                 where a.mode = 't'),
  'returns', format_type(p.prorettype, null),
  'retset', p.proretset) order by p.proname), '[]')
from pg_proc p join pg_namespace n on n.oid = p.pronamespace
where n.nspname = 'public' and p.prokind = 'f'
""")


def ts_scalar(pg: str) -> str:
    pg = pg.strip()
    if pg.endswith("[]"):
        inner = ts_scalar(pg[:-2])
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    base = pg.split(".")[-1]
    if base in enum_names:
        return f'Database["public"]["Enums"]["{base}"]'
    if base in ("smallint", "integer", "bigint", "numeric", "real", "double precision", "int2", "int4", "int8"):
        return "number"
    if base in ("boolean", "bool"):
        return "boolean"
    if base in ("json", "jsonb"):
        return "Json"
    if base == "void":
        return "undefined"
    return "string"


def column_type(col) -> str:
    if col["data_type"] == "ARRAY":
        return ts_scalar(col["udt"].lstrip("_") + "[]")
    if col["data_type"] == "USER-DEFINED":
        return ts_scalar(col["udt"])
    return ts_scalar(col["data_type"])


tables = {}
for col in columns:
    tables.setdefault(col["table"], []).append(col)

lines = []
w = lines.append
w("// Generated by scripts/local-db/gen-types.py from supabase/migrations.")
w("// Same shape as `supabase gen types typescript`; regenerate after changing migrations.")
w("")
w("export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]")
w("")
w("export type Database = {")
w("  public: {")
w("    Tables: {")
for name in sorted(tables):
    cols = tables[name]
    w(f"      {name}: {{")
    w("        Row: {")
    for c in cols:
        t = column_type(c)
        w(f"          {c['column']}: {t}{' | null' if c['nullable'] else ''}")
    w("        }")
    for kind in ("Insert", "Update"):
        w(f"        {kind}: {{")
        for c in cols:
            t = column_type(c)
            if c["identity"] and c["generated"] == "ALWAYS":
                w(f"          {c['column']}?: never")
                continue
            optional = kind == "Update" or c["nullable"] or c["default"] or c["identity"]
            w(f"          {c['column']}{'?' if optional else ''}: {t}{' | null' if c['nullable'] else ''}")
        w("        }")
    w("        Relationships: []")
    w("      }")
w("    }")
w("    Views: {")
w("      [_ in never]: never")
w("    }")
w("    Functions: {")
for fn in functions:
    if not fn["name"].startswith(RPC_PREFIXES):
        continue
    args = fn["args"] or []
    if args:
        arg_ts = "{ " + "; ".join(
            f"{a['name']}{'?' if a['has_default'] else ''}: {ts_scalar(a['type'])}" for a in args) + " }"
    else:
        arg_ts = "Record<PropertyKey, never>"
    if fn["table_cols"]:
        ret = "{ " + "; ".join(f"{c['name']}: {ts_scalar(c['type'])}" for c in fn["table_cols"]) + " }[]"
    else:
        ret = ts_scalar(fn["returns"]) + ("[]" if fn["retset"] else "")
    w(f"      {fn['name']}: {{")
    w(f"        Args: {arg_ts}")
    w(f"        Returns: {ret}")
    w("      }")
w("    }")
w("    Enums: {")
for e in enums:
    vals = " | ".join(json.dumps(v) for v in e["values"])
    w(f"      {e['name']}: {vals}")
w("    }")
w("    CompositeTypes: {")
w("      [_ in never]: never")
w("    }")
w("  }")
w("}")
w("")
w('type PublicSchema = Database["public"]')
w('export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"]')
w('export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"]')
w('export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"]')
w('export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T]')
w("")

out = os.path.join(ROOT, "src", "types", "database.ts")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w") as fh:
    fh.write("\n".join(lines))
print(f"wrote {out}: {len(tables)} tables, {len(enums)} enums", file=sys.stderr)
